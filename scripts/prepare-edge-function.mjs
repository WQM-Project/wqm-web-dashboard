import { readFileSync, mkdirSync, writeFileSync } from 'node:fs'

// Generate the deployable single file from the same code used by Next.js/tests.
const ingestion = readFileSync(new URL('../lib/server/ingest.ts', import.meta.url), 'utf8')
  .replace("from 'zod'", "from 'npm:zod@3.25.76'")
const storage = readFileSync(new URL('../lib/server/storage.ts', import.meta.url), 'utf8')
  .replace(/^import .*from '\.\/ingest'\r?\n/, '')
const entry = `// Generated by npm run edge:prepare. Edit lib/server source, then regenerate.
// Gateway authentication is performed in the handler; platform JWT verification
// must be disabled for this function because the Bearer value is a gateway key.
import { Buffer } from 'node:buffer'
${ingestion}
${storage}

const WQM_URL = 'https://scvcufiagvbeixhnwjze.supabase.co'
Deno.serve(async (request: Request): Promise<Response> => {
  if (request.method !== 'POST') return Response.json({ error: 'method_not_allowed' },
    { status: 405, headers: { Allow: 'POST', 'Cache-Control': 'no-store' } })
  const env = {
    SUPABASE_URL: Deno.env.get('SUPABASE_URL'),
    SUPABASE_SECRET_KEY: Deno.env.get('WQM_SUPABASE_SECRET_KEY'),
    SUPABASE_SERVICE_ROLE_KEY: Deno.env.get('SUPABASE_SERVICE_ROLE_KEY'),
  }
  if (env.SUPABASE_URL !== WQM_URL) return Response.json({ error: 'wrong_project' }, { status: 503 })
  return createIngestHandler({
    key: Deno.env.get('GATEWAY_INGEST_KEY'),
    allowedNodes: (Deno.env.get('GATEWAY_ALLOWED_NODE_IDS') ?? '').split(',').map(id => id.trim()).filter(Boolean),
    save: supabaseStorage(env),
  })(request)
})
`
const destination = new URL('../supabase/functions/ingest/index.ts', import.meta.url)
if (process.argv.includes('--check')) {
  if (readFileSync(destination, 'utf8') !== entry) throw new Error('Edge function is stale; run npm run edge:prepare')
  console.log('Edge function matches tested server source.')
} else {
  mkdirSync(new URL('../supabase/functions/ingest/', import.meta.url), { recursive: true })
  writeFileSync(destination, entry)
  console.log('Prepared WQM Edge Function: supabase/functions/ingest/index.ts')
}
